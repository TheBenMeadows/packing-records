#!/opt/homebrew/bin/uv run --script
# /// script
# requires-python = ">=3.11"
# dependencies = ["numpy==2.5.5", "scipy==1.18.1"]
# ///
"""Write the Lean data files for Cube10 from the trees written by gen_n10_run.py.
usage: gen_n10_emit.py <outdir with r*.json> <lean Packing dir> <reps per file>"""
import sys, json, glob, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gen_n10 as g
from gen_n10_run import classes, keyT

def sublists_len(n, l):
    def aux(n, l, f, r):
        if n == 0:
            return [f([])] + r
        if not l:
            return r
        a, rest = l[0], l[1:]
        return aux(n, rest, f, aux(n - 1, rest, lambda t, f=f, a=a: f([a] + t), r))
    return aux(n, l, lambda t: t, [])

HDR = '-- Generated by gen/gen_n10_emit.py from the trees of gen/gen_n10_run.py. Do not edit.\n'

def main():
    outdir, pdir, per = sys.argv[1], sys.argv[2], int(sys.argv[3])
    pats, rep_of, reps = classes()
    trees = {}
    for fn in glob.glob(os.path.join(outdir, 'r*.json')):
        d = json.load(open(fn))
        assert not d.get('fail'), fn
        trees[tuple(d['rep'])] = [tuple(x) if not isinstance(x, list) else x for x in d['nodes']]
    partial = len(sys.argv) > 4 and sys.argv[4] == 'partial'
    if not partial:
        assert len(trees) == len(reps), (len(trees), len(reps))
    ents = []
    for rep in reps:
        if rep not in trees:
            ents.append(None)
            continue
        out = []
        for nd in trees[rep]:
            nd = list(nd)
            if nd[0] == 'lp':
                out.append(('lp', [tuple(e) for e in nd[1]], list(nd[2])))
            else:
                out.append(tuple(nd))
        assert g.replay(out, g.root(list(rep))), rep
        ents.append(g.lean_ent(list(rep), out))
    # chunks by weight: nodes plus 30 per vertex-bound leaf
    bounds, acc, start = [], 0, 0
    for i, rep in enumerate(reps):
        nd = trees.get(rep, [])
        acc += len(nd) + 30 * sum(1 for x in nd if x[0] == 'lp')
        if acc >= per or i == len(reps) - 1:
            bounds.append((start, i + 1)); start = i + 1; acc = 0
    nfiles = len(bounds)
    names = []
    for k in range(nfiles):
        name = 'Cube10D%02d' % k
        names.append(name)
        chunk = ents[bounds[k][0]:bounds[k][1]]
        if any(c is None for c in chunk):
            continue
        if os.path.exists(os.path.join(pdir, name + '.lean')):
            continue
        src = HDR + 'import Packing.Cube10Check\n\nnamespace Packing.Cube10\n\n'
        src += 'noncomputable def R%02d : List Ent := [\n  ' % k + ',\n  '.join(chunk) + ']\n\n'
        src += 'set_option maxHeartbeats 0 in\ntheorem R%02d_ok : allK okEnt R%02d = true := by decide +kernel\n\nend Packing.Cube10\n' % (k, k)
        open(os.path.join(pdir, name + '.lean'), 'w').write(src)
    if partial:
        print('partial: wrote available chunks')
        return
    # symmetry table in the order of List.sublistsLen 10 (List.range 16)
    order = sublists_len(10, list(range(16)))
    assert len(order) == 8008 and len(set(map(tuple, order))) == 8008
    ridx = {rep: i for i, rep in enumerate(reps)}
    rows = []
    for pat in order:
        rep, t = rep_of[tuple(sorted(pat))]
        assert tuple(pat) == tuple(sorted(pat))
        assert tuple(sorted(keyT(t, k) for k in pat)) == rep
        rows.append('([%s], %d, %d)' % (', '.join(map(str, pat)), ridx[rep], t))
    rp = ['[%s]' % ', '.join(map(str, r)) for r in reps]
    rpb = [rp[i:i + 50] for i in range(0, len(rp), 50)]
    base = HDR + 'import Packing.Cube10Main\n\nnamespace Packing.Cube\n\nset_option maxRecDepth 100000\n\n'
    for k, blk in enumerate(rpb):
        base += 'def repPats%02d : List (List ℕ) := [\n  ' % k + ',\n  '.join(blk) + ']\n\n'
    base += '/-- The representative patterns, one for each pattern up to reflection. -/\n'
    base += 'def repPats : List (List ℕ) := ' + ' ++ '.join('repPats%02d' % k for k in range(len(rpb))) + '\n\n'
    base += 'theorem repPats_length : repPats.length = %d := by decide +kernel\n\nend Packing.Cube\n' % len(reps)
    open(os.path.join(pdir, 'Cube10SymBase.lean'), 'w').write(base)
    nb = 50
    blocks = [rows[i:i + nb] for i in range(0, len(rows), nb)]
    per_file = 20
    sfiles = []
    for f in range(0, len(blocks), per_file):
        fname = 'Cube10S%02d' % (f // per_file)
        sfiles.append(fname)
        src_s = HDR + 'import Packing.Cube10SymBase\n\nnamespace Packing.Cube\n\nset_option maxRecDepth 100000\nset_option maxHeartbeats 0\n\n'
        for k in range(f, min(f + per_file, len(blocks))):
            src_s += 'noncomputable def symTab%03d : List (List ℕ × ℕ × ℕ) := [\n  ' % k + ',\n  '.join(blocks[k]) + ']\n\n'
            src_s += ('theorem symTab%03d_ok : symTab%03d.all (fun q => decide (List.insertionSort (· ≤ ·)\n'
                      '    (q.1.map (keyT q.2.2)) = repPats.getD q.2.1 []) && decide (q.2.1 < %d)) = true := by\n'
                      '  decide +kernel\n\n') % (k, k, len(reps))
        src_s += 'end Packing.Cube\n'
        open(os.path.join(pdir, fname + '.lean'), 'w').write(src_s)
    sym = HDR + ''.join('import Packing.%s\n' % n for n in sfiles) + '\nnamespace Packing.Cube\n\nset_option maxRecDepth 100000\nset_option maxHeartbeats 0\n\n'
    sym += '/-- For each pattern, in the order of `List.sublistsLen`: the index of its representative and the\nreflection that maps it there. -/\n'
    sym += 'noncomputable def symTab : List (List ℕ × ℕ × ℕ) := ' + ' ++ '.join('symTab%03d' % k for k in range(len(blocks))) + '\n\n'
    sym += 'theorem symTab_fst : symTab.map Prod.fst = List.sublistsLen 10 (List.range 16) := by\n  decide +kernel\n\n'
    sym += 'theorem symTab_ok : symTab.all (fun q => decide (List.insertionSort (· ≤ ·) (q.1.map (keyT q.2.2))\n'
    sym += '    = repPats.getD q.2.1 []) && decide (q.2.1 < %d)) = true := by\n' % len(reps)
    sym += '  simp only [symTab, List.all_append, %s, Bool.and_self]\n\nend Packing.Cube\n' % ', '.join('symTab%03d_ok' % k for k in range(len(blocks)))
    open(os.path.join(pdir, 'Cube10Sym.lean'), 'w').write(sym)
    src = HDR + 'import Packing.Cube10Sym\n'
    src += ''.join('import Packing.%s\n' % n for n in names)
    src += '\nnamespace Packing.Cube\n\nopen Packing.Cube10\n\nset_option maxHeartbeats 0\nset_option maxRecDepth 100000\n\n'
    src += '/-- The checked proofs, one for each pattern up to reflection. -/\n'
    src += 'noncomputable def reps10 : List Ent := ' + ' ++ '.join('R%02d' % k for k in range(nfiles)) + '\n\n'
    src += 'theorem reps10_ok : ∀ e ∈ reps10, okEnt e = true := by\n'
    src += ''.join('  have e%02d : R%02d.all okEnt = true := by rw [← allK_eq]; exact R%02d_ok\n' % (k, k, k) for k in range(nfiles))
    src += '  have h : reps10.all okEnt = true := by\n'
    src += '    simp only [reps10, List.all_append, %s, Bool.and_self]\n' % ', '.join('e%02d' % k for k in range(nfiles))
    src += '  exact List.all_eq_true.1 h\n\n'
    src += 'theorem reps10_pats : reps10.map Ent.pat = repPats := by\n  decide +kernel\n\n'
    src += '''theorem reps10_cover : ∀ pat ∈ List.sublistsLen 10 (List.range 16), ∃ e ∈ reps10, ∃ τ : ℕ,
    List.insertionSort (· ≤ ·) (pat.map (keyT τ)) = e.pat := by
  intro pat hpat
  rw [← symTab_fst] at hpat
  obtain ⟨q, hq, rfl⟩ := List.mem_map.1 hpat
  have h := List.all_eq_true.1 symTab_ok q hq
  simp only [Bool.and_eq_true, decide_eq_true_eq] at h
  have hl : reps10.length = %d := by
    rw [← List.length_map (f := Ent.pat), reps10_pats, repPats_length]
  have hi : q.2.1 < reps10.length := by rw [hl]; exact h.2
  have hi' : q.2.1 < (reps10.map Ent.pat).length := by rw [List.length_map]; exact hi
  have e1 := List.getElem_of_eq reps10_pats hi'
  rw [List.getElem_map] at e1
  refine ⟨reps10[q.2.1], List.getElem_mem hi, q.2.2, ?_⟩
  rw [h.1, List.getD_eq_getElem _ _ (by rw [repPats_length]; exact h.2)]
  exact e1.symm

end Packing.Cube
''' % len(reps)
    open(os.path.join(pdir, 'Cube10Data.lean'), 'w').write(src)
    print('files', nfiles, 'reps', len(reps))

if __name__ == '__main__':
    main()
