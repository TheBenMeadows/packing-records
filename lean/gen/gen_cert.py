#!/opt/homebrew/bin/python3
"""Write the Lean certificate files for the Grassmannian cells.

Usage: gen_cert.py [CELL ...]

Reads cells.csv and grassmannian/*.txt from the repository root and writes, under
lean/:

  Packing/Cert/Cells/C_<m>_<n>_<N>.lean   one per cell: the configuration as data
                                          and one theorem, `check ... = true`,
                                          closed by kernel evaluation
  Packing/Cert/All.lean                   one `HasPacking` theorem per cell
  cells_manifest.tsv                      cell, m, n, N, proved k, table value k

With no CELL every Grassmannian cell is written. With CELLs only those cell
files are written, and All.lean and the manifest are left as they are.

The data of a cell are orthogonal integer frames, one per subspace, computed
here by exact integer Gram-Schmidt from the vectors in the cell's file. Lean
does not trust this step: `check` verifies that each frame is orthogonal.

The bound proved for a cell is k / 10^10, with k the largest integer the Lean
checker accepts. It must equal the cell's `our_value` rounded down to 10
decimals, or that minus one, and must exceed the table value.
"""
import csv
import os
import sys
from decimal import Decimal
from math import gcd

LEAN = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ROOT = os.path.dirname(LEAN)
sys.dont_write_bytecode = True  # check/__pycache__ is tracked; leave it alone
sys.path.insert(0, os.path.join(ROOT, 'check'))
import exact  # noqa: E402

D = 10 ** 40
SCALE = 10 ** 10


def dot(a, b):
    return sum(x * y for x, y in zip(a, b, strict=True))


def prim(v):
    g = 0
    for x in v:
        g = gcd(g, abs(x))
    return [x // g for x in v] if g else v


def gs(rows):
    """Pairwise orthogonal integer vectors with the same span as `rows`."""
    acc = []
    for b in rows:
        v = b
        for w, s in acc:
            c = dot(v, w)
            v = [s * x - c * y for x, y in zip(v, w, strict=True)]
        w = prim(v)
        acc.append((w, dot(w, w)))
    return acc


def pair_sum(F, G):
    """Packing.Cert.pairSum with D = 10^40."""
    return sum(dot(u, v) ** 2 * D // (s * t) + 1 for u, s in F for v, t in G)


def bound_k(frames, n):
    """The largest k that Packing.Cert.check accepts."""
    worst = max(pair_sum(F, G) for i, F in enumerate(frames) for G in frames[i + 1:])
    return n * SCALE - -(-worst // 10 ** 30)


def lean_vec(w, s):
    """A Packing.Cert.Vec: entries shifted by `off` to be nonnegative."""
    off = 10 ** len(str(max(abs(x) for x in w)))
    e = [x + off for x in w]
    return '⟨[%s], %d, %d, %d⟩' % (', '.join(str(x) for x in e), off, sum(e), s)


def lean_frames(frames):
    return '[\n' + ',\n'.join(
        '  [' + ', '.join(lean_vec(w, s) for w, s in F) + ']' for F in frames) + ']'


def cell_frames(cell):
    m, n, N = (int(x) for x in cell.split('-'))
    _, rows = exact.read_grassmannian(os.path.join(ROOT, 'grassmannian', cell + '.txt'), m, n, N)
    A, _ = exact.scale_rows(rows)
    return m, n, N, [gs(A[i * n:(i + 1) * n]) for i in range(N)]


def write_cell(outdir, cell):
    m, n, N, frames = cell_frames(cell)
    k = bound_k(frames, n)
    name = '%d_%d_%d' % (m, n, N)
    text = (
        '-- Generated by gen/gen_cert.py from grassmannian/%s.txt. Do not edit.\n'
        'import Packing.Cert.Check\n\n'
        'namespace Packing.Cert.Cells\n\n'
        '-- The list literal nests deeper than the default limit of the elaborator.\n'
        '-- `noncomputable`: no executable code is generated for the data, which keeps the\n'
        '-- compiled file about nine times smaller. The kernel evaluates it all the same.\n'
        'set_option maxRecDepth 100000 in\n'
        'noncomputable def c_%s : List Frame := %s\n\n'
        'theorem ok_%s : check %d %d %d %d c_%s = true := by decide +kernel\n\n'
        'end Packing.Cert.Cells\n' % (cell, name, lean_frames(frames), name, m, n, N, k, name))
    with open(os.path.join(outdir, 'C_%s.lean' % name), 'w') as f:
        f.write(text)
    return m, n, N, k


def floor_scaled(s):
    return int((Decimal(s) * SCALE).to_integral_value(rounding='ROUND_FLOOR'))


def check_row(cell, k, row):
    ours, listed = floor_scaled(row['our_value']), floor_scaled(row['table_value'])
    if k not in (ours, ours - 1):
        raise SystemExit('%s: bound %d disagrees with our_value %d' % (cell, k, ours))
    if k <= listed:
        raise SystemExit('%s: bound %d does not beat the table value %d' % (cell, k, listed))
    return listed


def write_all(done):
    lines = ['-- Generated by gen/gen_cert.py. Do not edit.', 'import Packing.Cert.Sound']
    lines += ['import Packing.Cert.Cells.C_%d_%d_%d' % (m, n, N) for _, m, n, N, _, _ in done]
    lines += ['', 'namespace Packing.Cert', '']
    for _, m, n, N, k, _ in done:
        lines += [
            '/-- %d subspaces of dimension %d in `ℝ^%d` at pairwise squared chordal distance at'
            ' least `%d / 10^10`. -/' % (N, n, m, k),
            'theorem packing_%d_%d_%d : HasPacking %d %d %d (%d / 10 ^ 10) := by'
            % (m, n, N, m, n, N, k),
            '  simpa only [Nat.cast_ofNat] using hasPacking_of_check Cells.ok_%d_%d_%d' % (m, n, N),
            '']
    lines += ['end Packing.Cert', '']
    with open(os.path.join(LEAN, 'Packing', 'Cert', 'All.lean'), 'w') as f:
        f.write('\n'.join(lines))


def main(argv):
    table = {r['cell']: r for r in csv.DictReader(open(os.path.join(ROOT, 'cells.csv')))
             if r['table'] == 'grassmannian'}
    outdir = os.path.join(LEAN, 'Packing', 'Cert', 'Cells')
    os.makedirs(outdir, exist_ok=True)
    done = []
    for cell in argv or sorted(table, key=lambda c: [int(x) for x in c.split('-')]):
        m, n, N, k = write_cell(outdir, cell)
        done.append((cell, m, n, N, k, check_row(cell, k, table[cell])))
    if argv:
        return 0
    write_all(done)
    with open(os.path.join(LEAN, 'cells_manifest.tsv'), 'w') as f:
        f.write('cell\tm\tn\tN\tk\ttable_k\n')
        f.write(''.join('%s\t%d\t%d\t%d\t%d\t%d\n' % row for row in done))
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
