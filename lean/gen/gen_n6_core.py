#!/opt/homebrew/bin/python3
"""Emit Packing/Cube6Core.lean: the two coordinate arguments of the six-point proof.

`layer_full`: four points in the four octants of the layer x3 <= 1/2 and two points in the
layer x3 >= 1/2 are not pairwise at squared distance more than 9/8.
`six_normal`: six points in the six octants other than (0,0,0) and (1,1,1) are not either.

Both follow Schaer 1966, pp. 275-280, with strict inequalities: two points in octants that
share a face are more than 3/4 apart across it (`push`), and a slab of height 1/4 holds at most
two points (`prism_three`). Standard library only; the output is plain text.

usage: gen_n6_core.py Packing/Cube6Core.lean
"""
import sys

IV = {'lo': ('0', '1 / 2'), 'hi': ('1 / 2', '1'), 'any': ('0', '1')}
P2 = '⟨by linarith, by linarith⟩'
L = '(by linarith)'


class Proof:
    def __init__(self, name, doc, cells, pairs):
        self.name, self.doc, self.cells, self.pairs = name, doc, cells, pairs
        self.order = list(cells)
        self.lines = []

    def c(self, P, k):
        return '%s%d' % (P.lower(), k)

    def pair(self, X, Y):
        X, Y = sorted((X, Y), key=self.order.index)
        assert (X, Y) in self.pairs, (X, Y)
        return 'h%s%s' % (X, Y)

    def header(self):
        out = ['/-- %s -/' % self.doc,
               'theorem %s {%s : ℝ}' % (self.name, ' '.join(self.c(P, k) for P in self.order for k in (1, 2, 3)))]
        for P in self.order:
            out.append('    ' + ' '.join('(h%s%d : %s ≤ %s ∧ %s ≤ %s)' % (
                P, k, IV[self.cells[P][k - 1]][0], self.c(P, k), self.c(P, k), IV[self.cells[P][k - 1]][1])
                for k in (1, 2, 3)))
        for X, Y in self.pairs:
            out.append('    (h%s%s : 9 / 8 < %s)' % (X, Y, ' + '.join(
                '(%s - %s) ^ 2' % (self.c(X, k), self.c(Y, k)) for k in (1, 2, 3))))
        out[-1] += ' : False := by'
        for P in self.order:
            for k in (1, 2, 3):
                out.append('  obtain ⟨l%s, u%s⟩ := h%s%d' % (self.c(P, k), self.c(P, k), P, k))
        return out

    def push(self, X, Y, k):
        """X is on the low side and Y on the high side of axis k; the other two cells agree."""
        k1, k2 = [j for j in (1, 2, 3) if j != k]
        for j in (k1, k2):
            assert self.cells[X][j - 1] == self.cells[Y][j - 1] != 'any'
        assert self.cells[X][k - 1] == 'lo' and self.cells[Y][k - 1] == 'hi'
        l1, l2 = IV[self.cells[X][k1 - 1]][0], IV[self.cells[X][k2 - 1]][0]
        self.lines.append('  obtain ⟨n%s%d, n%s%d⟩ := push %s %s %s %s %s %s (%s) (%s) %s %s %s %s %s %s %s (by linarith only [%s])' % (
            X, k, Y, k, self.c(X, k), self.c(Y, k), self.c(X, k1), self.c(Y, k1), self.c(X, k2), self.c(Y, k2),
            l1, l2, L, L, L, P2, P2, P2, P2, self.pair(X, Y)))

    def slab(self, X, Y, Z, k, side):
        """X and Y are in the slab of height 1/4 on `side` of axis k, so Z is not."""
        k1, k2 = [j for j in (1, 2, 3) if j != k]
        thin = (lambda P: self.c(P, k)) if side == 'lo' else (lambda P: '(1 - %s)' % self.c(P, k))
        args = ' '.join('%s %s %s' % (self.c(P, k1), self.c(P, k2), thin(P)) for P in (X, Y, Z))
        goal = '1 / 4 < %s' % self.c(Z, k) if side == 'lo' else '%s < 3 / 4' % self.c(Z, k)
        self.lines += ['  have m%s%d%s : %s := by' % (Z, k, side, goal),
                       '    by_contra hn',
                       '    push Not at hn',
                       '    exact prism_three %s %s (by linarith only [%s]) (by linarith only [%s]) (by linarith only [%s])' % (
                           args, ' '.join([P2] * 9), self.pair(X, Y), self.pair(X, Z), self.pair(Y, Z))]

    def text(self, ending):
        return '\n'.join(self.header() + self.lines + ending) + '\n'


HEADER = '''/-
The coordinate arguments for six points in the unit cube (Schaer 1966, pp. 275-280), with
strict inequalities.

Generated by gen/gen_n6_core.py.
-/
import Packing.Cube
import Packing.Cube6Cases

set_option linter.unusedVariables false
set_option maxHeartbeats 4000000

namespace Packing.Cube6

/-- Two points whose other two coordinates lie in common intervals of length `1/2`, at squared
distance more than `9/8`, are more than `3/4` apart in the remaining coordinate. -/
theorem push (a b u u' w w' l l' : ℝ) (ha : 0 ≤ a) (hab : a ≤ b) (hb : b ≤ 1)
    (hu : l ≤ u ∧ u ≤ l + 1 / 2) (hu' : l ≤ u' ∧ u' ≤ l + 1 / 2)
    (hw : l' ≤ w ∧ w ≤ l' + 1 / 2) (hw' : l' ≤ w' ∧ w' ≤ l' + 1 / 2)
    (h : 9 / 8 < (a - b) ^ 2 + (u - u') ^ 2 + (w - w') ^ 2) : a < 1 / 4 ∧ 3 / 4 < b := by
  have e1 : (u - u') ^ 2 ≤ (1 / 2) ^ 2 := sq_le_sq' (by linarith [hu.1, hu'.2]) (by linarith [hu.2, hu'.1])
  have e2 : (w - w') ^ 2 ≤ (1 / 2) ^ 2 := sq_le_sq' (by linarith [hw.1, hw'.2]) (by linarith [hw.2, hw'.1])
  have e3 : 3 / 4 < b - a := by
    by_contra hn
    push Not at hn
    have e4 : (b - a) ^ 2 ≤ (3 / 4) ^ 2 := sq_le_sq' (by linarith) hn
    linarith
  exact ⟨by linarith, by linarith⟩

/-- Three numbers in `[0, 3/4]` have squared differences summing to at most `9/8`. -/
theorem three_sq_le' {a b c : ℝ} (ha : 0 ≤ a ∧ a ≤ 3 / 4) (hb : 0 ≤ b ∧ b ≤ 3 / 4)
    (hc : 0 ≤ c ∧ c ≤ 3 / 4) : (a - b) ^ 2 + (a - c) ^ 2 + (b - c) ^ 2 ≤ 9 / 8 := by
  have h := Packing.Cube.three_sq_le (a := 4 / 3 * a) (b := 4 / 3 * b) (c := 4 / 3 * c)
    ⟨by linarith [ha.1], by linarith [ha.2]⟩ ⟨by linarith [hb.1], by linarith [hb.2]⟩
    ⟨by linarith [hc.1], by linarith [hc.2]⟩
  linarith

'''


def layer_full():
    cells = {'A': ('lo', 'lo', 'lo'), 'B': ('hi', 'lo', 'lo'), 'C': ('lo', 'hi', 'lo'),
             'D': ('hi', 'hi', 'lo'), 'E': ('any', 'any', 'hi'), 'F': ('any', 'any', 'hi')}
    pairs = [('A', 'B'), ('A', 'C'), ('A', 'E'), ('A', 'F'), ('B', 'D'), ('B', 'E'), ('B', 'F'),
             ('C', 'D'), ('C', 'E'), ('C', 'F'), ('D', 'E'), ('D', 'F'), ('E', 'F')]
    p = Proof('layer_full', 'If the four octants of the layer `x3 ≤ 1/2` each hold a point, two '
              'more points in the layer `x3 ≥ 1/2` cannot be far from all of them and from each other.',
              cells, pairs)
    p.push('A', 'B', 1)
    p.push('A', 'C', 2)
    p.push('B', 'D', 2)
    p.push('C', 'D', 1)
    for Z in ('E', 'F'):
        p.slab('A', 'C', Z, 1, 'lo')
        p.slab('B', 'D', Z, 1, 'hi')
        p.slab('A', 'B', Z, 2, 'lo')
        p.slab('C', 'D', Z, 2, 'hi')
    end = ['  have t%d : (e%d - f%d) ^ 2 ≤ (1 / 2) ^ 2 := sq_le_sq\' (by linarith) (by linarith)' % (k, k, k)
           for k in (1, 2, 3)]
    return p.text(end + ['  linarith'])


def six_normal():
    cells = {'P': ('hi', 'lo', 'lo'), 'Q': ('lo', 'hi', 'lo'), 'R': ('lo', 'lo', 'hi'),
             'S': ('hi', 'hi', 'lo'), 'U': ('hi', 'lo', 'hi'), 'V': ('lo', 'hi', 'hi')}
    pairs = [('P', 'Q'), ('P', 'R'), ('P', 'S'), ('P', 'U'), ('Q', 'R'), ('Q', 'S'), ('Q', 'V'),
             ('R', 'U'), ('R', 'V'), ('S', 'U'), ('S', 'V'), ('U', 'V')]
    p = Proof('six_normal', 'Six points in the six octants other than `(0,0,0)` and `(1,1,1)` '
              'are not pairwise at squared distance more than `9/8`.', cells, pairs)
    p.push('P', 'S', 2)
    p.push('P', 'U', 3)
    p.push('Q', 'S', 1)
    p.push('Q', 'V', 3)
    p.push('R', 'U', 1)
    p.push('R', 'V', 2)
    p.slab('S', 'U', 'P', 1, 'hi')
    p.slab('S', 'V', 'Q', 2, 'hi')
    p.slab('U', 'V', 'R', 3, 'hi')
    end = ['  have s%d := three_sq_le\' (a := p%d) (b := q%d) (c := r%d) %s %s %s' % (k, k, k, k, P2, P2, P2)
           for k in (1, 2, 3)]
    return p.text(end + ['  linarith'])


if __name__ == '__main__':
    open(sys.argv[1], 'w').write(HEADER + layer_full() + '\n' + six_normal() + '\nend Packing.Cube6\n')
    print('wrote', sys.argv[1])
