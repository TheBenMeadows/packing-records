#!/opt/homebrew/bin/python3
"""Emit Packing/Cube6Cases.lean: three points of the prism [0,1] x [0,1] x [0,1/4] are not
pairwise at squared distance more than 9/8.

The proof splits each point by the quadrant of the square it lies in (64 cases). Two points in
one quadrant are within 3/4 of each other. Three points in three quadrants are moved by the
reflections x -> 1 - x and y -> 1 - y and by a relabeling to the case of `prism_quadrants`.
Standard library only; the output is plain text.

usage: gen_n6_cases.py Packing/Cube6Cases.lean
       gen_n6_cases.py --ge Packing/Cube6CasesGe.lean   (distances at least 9/8: the three
                                                         points do not all lie below height 1/4)
"""
import itertools
import sys

HEADER = '''/-
Three points of the prism `[0,1] x [0,1] x [0,1/4]` are not pairwise at squared distance more
than `9/8` (Schaer 1966, pp. 275-280, Proposition 1, strict form).

Generated by gen/gen_n6_cases.py from `prism_quadrants`.
-/
import Packing.Cube6Prism

set_option linter.unusedVariables false
set_option maxHeartbeats 8000000

namespace Packing.Cube6

/-- Two points in one quadrant of the prism are at squared distance at most `9/16`. -/
theorem same_quadrant (x y z x' y' z' lx ly : ℝ) (hx : lx ≤ x ∧ x ≤ lx + 1 / 2)
    (hx' : lx ≤ x' ∧ x' ≤ lx + 1 / 2) (hy : ly ≤ y ∧ y ≤ ly + 1 / 2)
    (hy' : ly ≤ y' ∧ y' ≤ ly + 1 / 2) (hz : 0 ≤ z ∧ z ≤ 1 / 4) (hz' : 0 ≤ z' ∧ z' ≤ 1 / 4) :
    (x - x') ^ 2 + (y - y') ^ 2 + (z - z') ^ 2 ≤ 9 / 16 := by
  have e1 : (x - x') ^ 2 ≤ (1 / 2) ^ 2 := sq_le_sq' (by linarith [hx.1, hx'.2]) (by linarith [hx.2, hx'.1])
  have e2 : (y - y') ^ 2 ≤ (1 / 2) ^ 2 := sq_le_sq' (by linarith [hy.1, hy'.2]) (by linarith [hy.2, hy'.1])
  have e3 : (z - z') ^ 2 ≤ (1 / 4) ^ 2 := sq_le_sq' (by linarith [hz.1, hz'.2]) (by linarith [hz.2, hz'.1])
  linarith

theorem prism_three (x0 y0 z0 x1 y1 z1 x2 y2 z2 : ℝ)
    (hx0 : 0 ≤ x0 ∧ x0 ≤ 1) (hy0 : 0 ≤ y0 ∧ y0 ≤ 1) (hz0 : 0 ≤ z0 ∧ z0 ≤ 1 / 4)
    (hx1 : 0 ≤ x1 ∧ x1 ≤ 1) (hy1 : 0 ≤ y1 ∧ y1 ≤ 1) (hz1 : 0 ≤ z1 ∧ z1 ≤ 1 / 4)
    (hx2 : 0 ≤ x2 ∧ x2 ≤ 1) (hy2 : 0 ≤ y2 ∧ y2 ≤ 1) (hz2 : 0 ≤ z2 ∧ z2 ≤ 1 / 4)
    (h01 : 9 / 8 < (x0 - x1) ^ 2 + (y0 - y1) ^ 2 + (z0 - z1) ^ 2)
    (h02 : 9 / 8 < (x0 - x2) ^ 2 + (y0 - y2) ^ 2 + (z0 - z2) ^ 2)
    (h12 : 9 / 8 < (x1 - x2) ^ 2 + (y1 - y2) ^ 2 + (z1 - z2) ^ 2) : False := by
  obtain ⟨ax0, bx0⟩ := hx0
  obtain ⟨ay0, by0⟩ := hy0
  obtain ⟨az0, bz0⟩ := hz0
  obtain ⟨ax1, bx1⟩ := hx1
  obtain ⟨ay1, by1⟩ := hy1
  obtain ⟨az1, bz1⟩ := hz1
  obtain ⟨ax2, bx2⟩ := hx2
  obtain ⟨ay2, by2⟩ := hy2
  obtain ⟨az2, bz2⟩ := hz2
'''

L = '(by linarith)'
PAIR = '⟨by linarith, by linarith⟩'


def leaf(q):
    """q[i] = (qx, qy) of point i, each 0 (coordinate <= 1/2) or 1 (coordinate > 1/2)."""
    for i, j in ((0, 1), (0, 2), (1, 2)):
        if q[i] == q[j]:
            lx, ly = ('1 / 2' if q[i][0] else '0'), ('1 / 2' if q[i][1] else '0')
            return ('linarith [same_quadrant x%d y%d z%d x%d y%d z%d (%s) (%s) %s %s %s %s %s %s]'
                    % (i, i, i, j, j, j, lx, ly, PAIR, PAIR, PAIR, PAIR, PAIR, PAIR))
    missing = next(m for m in itertools.product((0, 1), repeat=2) if m not in q)
    fx, fy = missing[0] == 0, missing[1] == 0  # reflect so that the empty quadrant is (1, 1)
    r = [(qx ^ fx, qy ^ fy) for qx, qy in q]
    order = [r.index((0, 0)), r.index((1, 0)), r.index((0, 1))]
    args = []
    for i in order:
        args += ['(1 - x%d)' % i if fx else 'x%d' % i, '(1 - y%d)' % i if fy else 'y%d' % i, 'z%d' % i]
    dist = ['(by linarith only [h%d%d])' % (min(a, b), max(a, b))
            for a, b in ((order[0], order[1]), (order[0], order[2]), (order[1], order[2]))]
    if GE:
        return 'exact prism_quadrants_ge %s %s %s %s' % (' '.join(args), ' '.join([L] * 24),
                                                          ' '.join(dist), ' '.join([L] * 3))
    return 'exact prism_quadrants %s %s %s' % (' '.join(args), ' '.join([L] * 24), ' '.join(dist))


def tree(q, depth):
    pad = '  ' * (depth + 1)
    if depth == 6:
        return pad + leaf([(q[0], q[1]), (q[2], q[3]), (q[4], q[5])]) + '\n'
    v = '%s%d' % ('xy'[depth % 2], depth // 2)
    out = pad + 'rcases le_or_gt %s (1 / 2) with c%d | c%d\n' % (v, depth, depth)
    for b in (0, 1):
        sub = tree(q + [b], depth + 1)
        out += pad + '· ' + sub.lstrip()
    return out


