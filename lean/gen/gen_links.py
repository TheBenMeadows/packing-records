#!/opt/homebrew/bin/python3
"""Write the Lean link files for the Grassmannian cells.

Usage: gen_links.py [CELL ...]

A link file ties the frames of a cell file (Packing/Cert/Cells/C_<m>_<n>_<N>.lean,
written by gen_cert.py) to the vectors of grassmannian/<cell>.txt. It holds the
file's vectors, multiplied by one power of ten, and for every frame vector w the
integers g, p_k, q_k with g * w = sum_k (p_k - q_k) * b_k over the file's vectors
b_k of the same subspace. Lean checks these equations in the kernel.

Writes, under lean/:

  Packing/Cert/Cells/L_<m>_<n>_<N>.lean   one per cell
  Packing/Cert/AllLinks.lean              one `SpansPack` theorem per cell: the
                                          spans of the file's vectors have
                                          dimension n and the proved distance
  links_manifest.tsv                      cell, k, sha256 of the data file

With no CELL every Grassmannian cell is written. With CELLs only those link
files are written, and AllLinks.lean and the manifest are left as they are.

The bound k of a cell is read from cells_manifest.tsv. Each data file must have
the sha256 that cells.csv records.
"""
import csv
import os
import sys
from fractions import Fraction
from math import gcd, lcm

sys.dont_write_bytecode = True  # check/__pycache__ is tracked; leave it alone
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gen_cert import LEAN, ROOT, dot, exact, gs  # noqa: E402
from gen_points import lean_vec, pinned_sha  # noqa: E402


def link_frame(rows):
    """Frame vectors and their (g, [(p, q)]) coefficients over `rows`."""
    acc = []
    for j, b in enumerate(rows):
        v, cv = b, [Fraction(int(i == j)) for i in range(len(rows))]
        for w, s, cw in acc:
            c = dot(v, w)
            v = [s * x - c * y for x, y in zip(v, w, strict=True)]
            cv = [s * a - c * b for a, b in zip(cv, cw, strict=True)]
        g = 0
        for x in v:
            g = gcd(g, abs(x))
        if g == 0:
            raise SystemExit('linearly dependent vectors in a subspace')
        w = [x // g for x in v]
        acc.append((w, dot(w, w), [a / g for a in cv]))
    out = []
    for w, _, cw in acc:
        big = lcm(*[a.denominator for a in cw])
        ints = [int(a * big) for a in cw]
        for i in range(len(w)):
            if big * w[i] != sum(t * b[i] for t, b in zip(ints, rows, strict=True)):
                raise SystemExit('coefficients do not reproduce a frame vector')
        out.append((w, big, [(max(t, 0), max(-t, 0)) for t in ints]))
    return out


def lean_coef(big, pq):
    return '⟨%d, [%s]⟩' % (big, ', '.join('(%d, %d)' % x for x in pq))


def write_cell(outdir, cell, row):
    sha = pinned_sha(row)
    m, n, N = (int(x) for x in cell.split('-'))
    _, rows = exact.read_grassmannian(os.path.join(ROOT, row['file']), m, n, N)
    A, _ = exact.scale_rows(rows)
    blocks = [A[i * n:(i + 1) * n] for i in range(N)]
    linked = [link_frame(B) for B in blocks]
    for B, L in zip(blocks, linked, strict=True):
        if [w for w, _, _ in L] != [w for w, _ in gs(B)]:
            raise SystemExit('%s: frames differ from gen_cert.gs' % cell)
    name = '%d_%d_%d' % (m, n, N)
    rows_lean = '[\n' + ',\n'.join(
        '  [' + ', '.join(lean_vec(b) for b in B) + ']' for B in blocks) + ']'
    coef_lean = '[\n' + ',\n'.join(
        '  [' + ', '.join(lean_coef(big, pq) for _, big, pq in L) + ']' for L in linked) + ']'
    text = (
        '-- Generated by gen/gen_links.py from grassmannian/%s.txt. Do not edit.\n'
        'import Packing.Cert.CheckLink\n'
        'import Packing.Cert.Cells.C_%s\n\n'
        'namespace Packing.Cert.Cells\n\n'
        '-- The vectors of the file, multiplied by one power of ten.\n'
        'set_option maxRecDepth 100000 in\n'
        'noncomputable def r_%s : List Frame := %s\n\n'
        '-- For each frame vector `w` of `c_%s`: `g` and the pairs `(p, q)` with\n'
        '-- `g * w = sum (p - q) * b` over the file vectors `b` of the same subspace.\n'
        'set_option maxRecDepth 100000 in\n'
        'noncomputable def k_%s : List (List Coef) := %s\n\n'
        'theorem link_%s : checkLink %d %d r_%s c_%s k_%s = true := by decide +kernel\n\n'
        'end Packing.Cert.Cells\n'
        % (cell, name, name, rows_lean, name, name, coef_lean, name, m, n, name, name, name))
    with open(os.path.join(outdir, 'L_%s.lean' % name), 'w') as f:
        f.write(text)
    return m, n, N, sha


def write_all(done):
    lines = ['-- Generated by gen/gen_links.py. Do not edit.', 'import Packing.Cert.SoundLink']
    lines += ['import Packing.Cert.Cells.L_%d_%d_%d' % (m, n, N) for _, m, n, N, _, _ in done]
    lines += ['', 'namespace Packing.Cert', '']
    for _, m, n, N, k, _ in done:
        lines += [
            '/-- The %d subspaces spanned by the vectors of `grassmannian/%d-%d-%d.txt` have'
            ' dimension %d and are pairwise at squared chordal distance at least'
            ' `%d / 10^10`. -/' % (N, m, n, N, n, k),
            'theorem packing_file_%d_%d_%d : SpansPack %d %d (%d / 10 ^ 10) Cells.r_%d_%d_%d := by'
            % (m, n, N, m, n, k, m, n, N),
            '  simpa only [Nat.cast_ofNat] using',
            '    (spansPack_of_link Cells.ok_%d_%d_%d Cells.link_%d_%d_%d).2' % (m, n, N, m, n, N),
            '']
    lines += ['end Packing.Cert', '']
    with open(os.path.join(LEAN, 'Packing', 'Cert', 'AllLinks.lean'), 'w') as f:
        f.write('\n'.join(lines))


def main(argv):
    table = {r['cell']: r for r in csv.DictReader(open(os.path.join(ROOT, 'cells.csv')))
             if r['table'] == 'grassmannian'}
    bounds = {r['cell']: int(r['k']) for r in csv.DictReader(
        open(os.path.join(LEAN, 'cells_manifest.tsv')), delimiter='\t')}
    outdir = os.path.join(LEAN, 'Packing', 'Cert', 'Cells')
    os.makedirs(outdir, exist_ok=True)
    done = []
    for cell in argv or sorted(table, key=lambda c: [int(x) for x in c.split('-')]):
        m, n, N, sha = write_cell(outdir, cell, table[cell])
        done.append((cell, m, n, N, bounds[cell], sha))
    if argv:
        return 0
    write_all(done)
    with open(os.path.join(LEAN, 'links_manifest.tsv'), 'w') as f:
        f.write('cell\tk\tsha256\n')
        f.write(''.join('%s\t%d\t%s\n' % (cell, k, sha) for cell, _, _, _, k, sha in done))
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
