"""Emit Packing/Cube8Cert.lean: where the edge inequality of the eight-point proof is tight.

For one coordinate, s0..s3 lie in [0, 1/2] and t0..t3 in [1/2, 1]. The twelve squared
differences along the edges of the cube graph sum to at most 4 (`edge_sum_le`). That bound is
also attained with a pair s_i = t_i = 1/2, so the lemma adds t_i - s_i >= 7/10, which holds for
points in adjacent half-cubes at distance at least 1. Then the sum is 4 only for s_i = 0 and
t_i = 1: the certificate is an identity
    4 - E - eps * sum_i (s_i + 1 - t_i) = c_0 + sum_k c_k * (product of constraints),  c_k >= 0,
found by a floating-point LP and checked in exact arithmetic (functions of gen_n5.py).

usage: gen_n8_unique.py <output .lean>      (run from lean/gen; Linux only, 2 GB cap)
"""
import sys
from fractions import Fraction as F

from gen_n5 import certificate, lean_lin, linpoly, padd, pmul

V = ['s0', 's1', 's2', 's3', 't0', 't1', 't2', 't3']
S, T = [0, 1, 2, 3], [4, 5, 6, 7]

cons = []
for i in range(4):
    cons += [linpoly(0, {S[i]: 1}), linpoly(F(1, 2), {S[i]: -1}),
             linpoly(F(-1, 2), {T[i]: 1}), linpoly(1, {T[i]: -1}),
             linpoly(F(-7, 10), {T[i]: 1, S[i]: -1})]
diffs = [linpoly(0, {T[i]: 1, S[i]: -1}) for i in range(4)]
diffs += [linpoly(0, {S[i]: 1, S[(i + 1) % 4]: -1}) for i in range(4)]
diffs += [linpoly(0, {T[i]: 1, T[(i + 1) % 4]: -1}) for i in range(4)]
target = {(): F(4)}
for g in diffs:
    target = padd(target, pmul(g, g), -1)
L = {}
for i in range(4):
    L = padd(L, cons[5 * i])
    L = padd(L, cons[5 * i + 3])

found = None
for eps in (F(1, 2), F(1, 4), F(1, 8), F(1, 16), F(1, 64)):
    found = certificate(8, cons, padd(target, {m: c * eps for m, c in L.items()}, -1), (2, 3))
    if found:
        break
assert found, 'no certificate'
print('edge_sum_eq: eps %s, degree %d, %d terms' % (eps, found[0], len(found[1])), flush=True)

hints = []
for combo, _ in found[1]:
    if len(combo) < 2:
        continue
    t = 'h%d' % combo[0]
    for k in combo[1:]:
        t = 'mul_nonneg (%s) h%d' % (t, k) if t.startswith('mul') else 'mul_nonneg %s h%d' % (t, k)
    hints.append(t)
E = ('(t0 - s0) ^ 2 + (t1 - s1) ^ 2 + (t2 - s2) ^ 2 + (t3 - s3) ^ 2\n'
     '      + (s0 - s1) ^ 2 + (s1 - s2) ^ 2 + (s2 - s3) ^ 2 + (s3 - s0) ^ 2\n'
     '      + (t0 - t1) ^ 2 + (t1 - t2) ^ 2 + (t2 - t3) ^ 2 + (t3 - t0) ^ 2')
lines = ['/-', 'Where the edge inequality of the eight-point proof is tight.', '',
         'Generated by gen/gen_n8_unique.py.', '-/', 'import Mathlib', '',
         'set_option linter.unusedVariables false', 'set_option maxRecDepth 10000', '',
         'namespace Packing.Cube8', '',
         '/-- With `t i - s i ≥ 7/10`, the twelve squared differences of `edge_sum_le` sum to `4`',
         'only for `s i = 0` and `t i = 1`. -/',
         'theorem edge_sum_eq (%s : ℝ)' % ' '.join(V)]
lines += ['    (h%d : 0 ≤ %s)' % (i, lean_lin(g, V)) for i, g in enumerate(cons)]
lines += ['    (hd : 4 ≤ %s) :' % E,
          '    s0 = 0 ∧ s1 = 0 ∧ s2 = 0 ∧ s3 = 0 ∧ t0 = 1 ∧ t1 = 1 ∧ t2 = 1 ∧ t3 = 1 := by',
          '  have hL : %s ≤ 0 := by' % lean_lin(L, V),
          '    linarith [' + ',\n      '.join(hints) + ']',
          '  exact ⟨by linarith, by linarith, by linarith, by linarith, by linarith, by linarith,',
          '    by linarith, by linarith⟩', '', 'end Packing.Cube8', '']
open(sys.argv[1], 'w').write('\n'.join(lines))
print('wrote', sys.argv[1])
