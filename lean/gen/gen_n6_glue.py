def cellstr(v):
    return '(%s, %s, %s)' % tuple(B[x] for x in v)


def fetch(pad, names):
    """names: dict letter -> cell. Lean lines that pick the point of each cell and its bounds."""
    out = []
    for X, v in names.items():
        out += ['obtain ⟨i%s, h%s⟩ := hocc %s (by decide) (by decide)' % (X, X, cellstr(v)),
                'have b%s := cell_bounds (hp i%s) h%s' % (X, X, X),
                'simp only [%s] at b%s' % (', '.join((['lo_false', 'hi_false'] if 0 in v else [])
                                                    + (['lo_true', 'hi_true'] if 1 in v else [])), X),
                'obtain ⟨⟨l%s0, u%s0⟩, ⟨l%s1, u%s1⟩, ⟨l%s2, u%s2⟩⟩ := b%s' % (X, X, X, X, X, X, X)]
    return [pad + l for l in out]


def dists(pad, pairs):
    out = []
    for X, Y in pairs:
        out += ['have d%s%s := %s i%s i%s (by intro h; rw [h] at h%s; exact absurd (h%s.symm.trans h%s) (by decide))'
                % (X, Y, 'hsq' if GE else 'hcon', X, Y, X, X, Y),
                'rw [dist_sq] at d%s%s' % (X, Y)]
    return [pad + l for l in out]


def call(pad, lemma, coords, pairs):
    """coords: list of (letter, axis, reflected)."""
    terms = ' '.join('(1 - p i%s %d)' % (X, k) if r else '(p i%s %d)' % (X, k) for X, k, r in coords)
    hyps = ' '.join('⟨by linarith only [l%s%d, u%s%d], by linarith only [l%s%d, u%s%d]⟩'
                    % (X, k, X, k, X, k, X, k) for X, k, _ in coords)
    ds = ' '.join('(by linarith only [d%s%s])' % pr for pr in pairs)
    return [pad + 'exact @%s %s %s %s' % (lemma, terms, hyps, ds)]


def leaf(e1, e2, pad):
    if e1 == e2:
        return [pad + 'exact absurd rfl hne']
    same = [k for k in range(3) if e1[k] == e2[k]]
    if not same and GE:
        return [pad + 'rfl']
    if not same:  # opposite: reflect the axes where e1 is true
        base = {'P': (1, 0, 0), 'Q': (0, 1, 0), 'R': (0, 0, 1), 'S': (1, 1, 0), 'U': (1, 0, 1), 'V': (0, 1, 1)}
        names = {X: tuple(v[k] ^ e1[k] for k in range(3)) for X, v in base.items()}
        coords = [(X, k, bool(e1[k])) for X in names for k in range(3)]
        return fetch(pad, names) + dists(pad, SIX_PAIRS) + call(pad, 'six_normal', coords, SIX_PAIRS)
    k = same[0]
    full = 1 - e1[k]  # the layer of axis k opposite to the empty half-cubes is full
    k1, k2 = [j for j in range(3) if j != k]

    def mk(b1, b2, bk):
        v = [0, 0, 0]
        v[k1], v[k2], v[k] = b1, b2, bk
        return tuple(v)

    names = {'A': mk(0, 0, full), 'B': mk(1, 0, full), 'C': mk(0, 1, full), 'D': mk(1, 1, full)}
    rest = [mk(b1, b2, 1 - full) for b1, b2 in itertools.product((0, 1), repeat=2)]
    rest = [v for v in rest if v not in (e1, e2)]
    assert len(rest) == 2
    names['E'], names['F'] = rest
    coords = []
    for X in names:
        coords += [(X, k1, False), (X, k2, False), (X, k, bool(full))]
    if GE:
        return [pad + 'exfalso'] + fetch(pad, names) + dists(pad, LAYER_PAIRS) + call(
            pad, 'layer_full_ge', coords, LAYER_PAIRS)
    return fetch(pad, names) + dists(pad, LAYER_PAIRS) + call(pad, 'layer_full', coords, LAYER_PAIRS)


def tree(bits, depth):
    pad = '  ' * (depth + 1)
    if depth == 6:
        return leaf(tuple(bits[:3]), tuple(bits[3:]), pad)
    var = ['a', 'b', 'c', "a'", "b'", "c'"][depth]
    out = [pad + 'cases %s' % var]
    for bit in (0, 1):
        sub = tree(bits + [bit], depth + 1)
        out.append(pad + '· ' + sub[0].lstrip())
        out += sub[1:]
    return out


